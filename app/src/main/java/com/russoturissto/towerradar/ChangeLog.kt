package com.russoturissto.towerradar

/** Bundled release notes always work without connectivity. */
object ChangeLog {
    fun forVersion(version: String): String = when (version) {
        "0.27.1" -> listOf(
            "• Координаты центра карты вынесены под верхнюю панель: жёлтый цвет и копирование по нажатию.",
            "• Исправлены значки высоты и вышки в раскрывающемся меню.",
            "• Кнопки «+» и GPS больше не перемещаются при раскрытии меню.",
            "• Компас плавно поднимается при открытии меню и опускается при закрытии.",
            "• Отключён поворот TowerRadar в горизонтальную ориентацию.",
            "• Кеш просмотренных карт: 100, 250, 500 МБ или «Без ограничений»."
        ).joinToString("\n")

        "0.27.0" -> listOf(
            "• Подтверждение установки тестовых APK (Да / Нет).",
            "• Быстрые действия: добавить вышку и узнать высоту центра карты.",
            "• Выбор офлайн-области по масштабу карты; радиусы 10 и 30 км.",
            "• Помощник подключения API-ключей при первом запуске.",
            "• История изменений доступна из настроек."
        ).joinToString("\n")
        else -> "Для этой версии список изменений недоступен."
    }
}
